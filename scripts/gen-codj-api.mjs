#!/usr/bin/env node
// Generates the co-DJ API surfaces from the ONE command registry (src/agentkit/Commands.tish):
//   public/codj.d.ts                 the script API types (served at /codj.d.ts; in every agent prompt)
//   docs/CODJ_API.md                 the reference (hooks, hosts, command/tool table)
//   src/agentkit/PromptAssets.tish   skills/*.md + docs/DECK_AGENT_GRAMMAR.md + codj.d.ts, embedded for the browser
// and checks llms.txt links the reference.
//
//   node scripts/gen-codj-api.mjs           write
//   node scripts/gen-codj-api.mjs --check   exit 1 if anything is stale (CI / test:js)

import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const tish = join(root, 'node_modules/.bin/tish');
const out = join(mkdtempSync(join(tmpdir(), 'codj-api-')), 'dump.mjs');
execFileSync(tish, ['build', '--target', 'js', join(root, 'scripts/codj-api-dump.tish'), '-o', out], { stdio: ['ignore', 'ignore', 'inherit'] });
const dump = JSON.parse(execFileSync(process.execPath, [out], { encoding: 'utf8' }));

const toolList = dump.tools
  .map((t) => `- \`${t.name}\`${t.readOnly ? ' (read)' : ''} — ${t.description}`)
  .join('\n');

const apiMd = `<!-- GENERATED by scripts/gen-codj-api.mjs from src/agentkit/Commands.tish — edit the registry, not this file. -->
# Co-DJ API — scripts, tools, hosts

An AI (or human) co-DJ is a **program**: a small JavaScript script whose hooks run against the live room every bar.
The same capabilities are exposed three ways, all generated from one registry
([src/agentkit/Commands.tish](../src/agentkit/Commands.tish)):

- **Script API** — \`codj.<name>(…)\` inside a co-DJ script (types: [public/codj.d.ts](../public/codj.d.ts), served at \`/codj.d.ts\`).
- **LLM tools** — the built-in Hypery co-DJ agent calls them (plus \`write_script\` / \`read_script\` / \`run_script\` / \`script_logs\`).
- **MCP tools** — \`pnpm run mcp\` exposes the same tools to Cursor / Claude ([services/mcp/main.tish](../services/mcp/main.tish)).

Agents are better at writing code than at driving long tool sequences, so the intended loop is: **read the room,
write the script, read its logs** — the script then plays on its own, bar after bar, and is rewritten when the
music (or the chat) calls for it.

## A script

\`\`\`js
// examples/codj/hat-evolver.js
export function setup(codj) {
  if (!codj.owned().length) codj.state.hat = codj.addTrack({ name: 'Hat', gen: 'noise_burst', steps: '..x...x...x...x.' }).id
}
export function onBar(codj, ctx) {
  const fill = ctx.bar % 8 === 7
  codj.setSteps(codj.state.hat, fill ? 'x.xxx.xxx.xxx.xx' : '..x...x...x...x.')
}
\`\`\`

| hook | when | writes land |
|---|---|---|
| \`setup(codj, ctx)\` | once per (re)load, after the room snapshot | now |
| \`onBar(codj, ctx)\` | every bar while playing (\`ctx.bar\`) | next bar |
| \`onBeat(codj, ctx)\` | every beat while playing (\`ctx.beat\`) | next beat |
| \`onMessage(codj, ctx)\` | someone chatted (\`ctx.message\`, \`.toMe\`) | next bar |
| \`onEvent(codj, ctx)\` | anything else the room published (\`ctx.event\`) | next bar |

\`codj.state\` survives hot reloads; \`codj.log(…)\` goes to the co-DJ's log. A script that fails to load (or whose
\`setup\` throws) never replaces the running one; one that throws three times in a row rolls back to the last good
source. Hooks have a 50 ms budget (enforced with \`node:vm\` in the CLI; the browser worker is watchdogged).

## Hosts

| host | how | identity |
|---|---|---|
| Browser | Co-DJ panel → **Add AI co-DJ** (producer) or **Add AI host** (session, booth, fader, echo/filter) — a Web Worker; loopback to this page, or the room when connected | your Hypery login |
| CLI | \`pnpm run codj -- run examples/codj/hat-evolver.js --session <id> [--agent]\` (file-watch hot reload) | \`pnpm run codj:login\` (browser login) |
| MCP | \`pnpm run mcp\` — tools for Cursor / Claude, same registry | \`pnpm run codj:login\` |

Everything a co-DJ sees comes from what the host publishes (deck deltas, snapshots, ticks, chat, edit results —
[STREAM_PROTOCOL.md §7](STREAM_PROTOCOL.md)); everything it does is deck text through the host's one gated ingest.

## Commands

${dump.table}
## Tools (LLM / MCP names)

${toolList}
`;

function tishString(s) {
  return JSON.stringify(s);
}

const skillsDir = join(root, 'skills');
const skillFiles = readdirSync(skillsDir).filter((f) => f.endsWith('.md') && f !== 'README.md').sort();
const skillEntries = skillFiles
  .map((f) => `    ${tishString(f.replace(/\.md$/, ''))}: ${tishString(readFileSync(join(skillsDir, f), 'utf8'))}`)
  .join(',\n');
const grammar = readFileSync(join(root, 'docs/DECK_AGENT_GRAMMAR.md'), 'utf8');
const assets = `// GENERATED by scripts/gen-codj-api.mjs — skills/*.md + docs/DECK_AGENT_GRAMMAR.md + public/codj.d.ts, embedded so the
// browser co-DJ worker composes the same prompt as the CLI. Edit the sources and re-run the generator.

export fn promptAssets() {
  return {
    grammar: ${tishString(grammar)},
    dts: ${tishString(dump.dts)},
    skills: {
${skillEntries}
    }
  }
}
`;

const targets = [
  ['public/codj.d.ts', dump.dts],
  ['docs/CODJ_API.md', apiMd],
  ['src/agentkit/PromptAssets.tish', assets],
];

let stale = [];
for (const [rel, text] of targets) {
  const p = join(root, rel);
  const cur = existsSync(p) ? readFileSync(p, 'utf8') : null;
  if (cur === text) continue;
  if (check) stale.push(rel);
  else {
    writeFileSync(p, text);
    console.log('wrote', rel);
  }
}

const llms = readFileSync(join(root, 'llms.txt'), 'utf8');
if (!llms.includes('docs/CODJ_API.md')) stale.push('llms.txt (missing docs/CODJ_API.md link)');

if (stale.length) {
  console.error((check ? 'co-DJ API docs are stale — run `node scripts/gen-codj-api.mjs`:\n  ' : 'needs attention:\n  ') + stale.join('\n  '));
  process.exit(1);
}
if (check) console.log('co-DJ API docs up to date (' + dump.tools.length + ' commands)');
